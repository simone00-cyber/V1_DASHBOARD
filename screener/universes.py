def fallback_universe(name: str) -> pd.DataFrame:
    records = _FALLBACKS.get(name)
    if not records:
        return pd.DataFrame(columns=["Company", "Ticker", "Sector"])

    frame = pd.DataFrame(records, columns=["Company", "Ticker", "Sector"])
    spec = UNIVERSES[name]
    frame["Ticker"] = frame["Ticker"].map(lambda value: normalize_ticker(value, spec))
    return frame.drop_duplicates("Ticker").reset_index(drop=True)


def load_universe(name: str, timeout: int = 15) -> tuple[pd.DataFrame, str]:
    if name not in UNIVERSES:
        raise KeyError(f"Unknown universe: {name}")

    spec = UNIVERSES[name]
    if spec.parser is None:
        raise ValueError(f"Parser not configured for universe: {name}")

    try:
        response = requests.get(
            spec.source_url,
            timeout=timeout,
            headers={"User-Agent": "Cyclical-Terminal/1.0"},
        )
        response.raise_for_status()
        tables = pd.read_html(StringIO(response.text))
        frame = spec.parser(tables, spec)
        if len(frame) < 20:
            raise ValueError("Constituent table unexpectedly small.")
        return frame, spec.source_url
    except Exception:
        fallback = fallback_universe(name)
        if fallback.empty:
            raise
        return fallback, "bundled fallback snapshot"
