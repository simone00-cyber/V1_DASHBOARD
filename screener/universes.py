from __future__ import annotations

from dataclasses import dataclass
from io import StringIO
from typing import Callable

import pandas as pd
import requests


@dataclass(frozen=True)
class UniverseSpec:
    name: str
    source_url: str
    suffix: str = ""
    dot_to_dash: bool = False
    parser: Callable[[list[pd.DataFrame], "UniverseSpec"], pd.DataFrame] | None = None
    benchmark_ticker: str = ""


def _clean_columns(frame: pd.DataFrame) -> pd.DataFrame:
    result = frame.copy()
    result.columns = [
        str(col[-1] if isinstance(col, tuple) else col).strip()
        for col in result.columns
    ]
    return result


def _find_table(tables: list[pd.DataFrame], required_any: tuple[str, ...]) -> pd.DataFrame:
    for raw in tables:
        frame = _clean_columns(raw)
        names = {str(column).lower() for column in frame.columns}
        if all(any(token in name for name in names) for token in required_any):
            return frame
    raise ValueError("Constituent table not found in source page.")


def _pick_column(frame: pd.DataFrame, candidates: tuple[str, ...]) -> str | None:
    for candidate in candidates:
        for column in frame.columns:
            if candidate in str(column).lower():
                return str(column)
    return None


def normalize_ticker(value: object, spec: UniverseSpec) -> str:
    """Convert a source ticker into the Yahoo Finance symbol for the universe."""
    ticker = str(value).strip().upper()

    if not ticker or ticker in {"NAN", "NONE", "<NA>"}:
        return ""

    ticker = ticker.replace(" ", "")

    if spec.suffix:
        suffix = spec.suffix.upper()
        dashed_suffix = suffix.replace(".", "-")

        # Repair malformed symbols generated by older code, e.g. A2A-MI.MI.
        while ticker.endswith(suffix):
            ticker = ticker[: -len(suffix)]
        while dashed_suffix and ticker.endswith(dashed_suffix):
            ticker = ticker[: -len(dashed_suffix)]

        ticker = f"{ticker}{suffix}"
    elif spec.dot_to_dash:
        # Yahoo uses dashes for US share classes: BRK.B -> BRK-B.
        ticker = ticker.replace(".", "-")

    return ticker


def _standardize(frame: pd.DataFrame, spec: UniverseSpec) -> pd.DataFrame:
    company_col = _pick_column(frame, ("company", "constituent", "security", "name"))
    ticker_col = _pick_column(frame, ("ticker", "symbol", "epic"))
    sector_col = _pick_column(frame, ("gics sector", "icb sector", "industry", "sector"))

    if not company_col or not ticker_col:
        raise ValueError("Company/ticker columns not available.")

    result = pd.DataFrame(
        {
            "Company": (
                frame[company_col]
                .astype(str)
                .str.replace(r"\[.*?\]", "", regex=True)
                .str.strip()
            ),
            "Ticker": (
                frame[ticker_col]
                .astype(str)
                .str.replace(r"\[.*?\]", "", regex=True)
                .str.strip()
            ),
            "Sector": (
                frame[sector_col].astype(str).str.strip()
                if sector_col
                else "Unclassified"
            ),
        }
    )

    result["Ticker"] = result["Ticker"].map(lambda value: normalize_ticker(value, spec))

    return (
        result.replace({"nan": pd.NA, "None": pd.NA, "": pd.NA})
        .dropna(subset=["Ticker"])
        .drop_duplicates("Ticker")
        .reset_index(drop=True)
    )


def _parse_sp500(tables: list[pd.DataFrame], spec: UniverseSpec) -> pd.DataFrame:
    return _standardize(_find_table(tables, ("symbol", "security")), spec)


def _parse_nasdaq100(tables: list[pd.DataFrame], spec: UniverseSpec) -> pd.DataFrame:
    return _standardize(_find_table(tables, ("ticker", "company")), spec)


def _parse_ftse_mib(tables: list[pd.DataFrame], spec: UniverseSpec) -> pd.DataFrame:
    return _standardize(_find_table(tables, ("ticker", "company")), spec)


def _parse_dax(tables: list[pd.DataFrame], spec: UniverseSpec) -> pd.DataFrame:
    return _standardize(_find_table(tables, ("ticker", "company")), spec)


